export function getDemoReport(id: DemoId, lang: Lang): Report {
  const c = CACHE[id];
  const raw = {
    company_name: c.company_name,
    contact_email: c.contact_email,
    summary: c.summary[lang],
    risk_score: c.risk_score,
    data_categories: Object.entries(c.cats).map(([category, [collected, d]]) => ({
      category,
      collected,
      details: d[lang],
    })),
    other_data: c.other.map((o) => o[lang]),
    third_parties: c.parties.map(([recipient, type, purpose, cross_border]) => ({
      recipient: recipient[lang],
      type,
      purpose: purpose[lang],
      cross_border,
    })),
    retention: { period: c.retention[0][lang], can_delete: c.retention[1], how_to_delete: c.retention[2][lang] },
    red_flags: c.flags.map(([title, quote, explanation], i) => ({
      title: title[lang],
      quote,
      explanation: explanation[lang],
      action: c.actions[i]?.[lang] ?? "",
    })),
    risk_factors: c.factors.map(([factor, points]) => ({ factor: factor[lang], points })),
    user_rights: Object.entries(c.rights).map(([right, [available, d]]) => ({ right, available, details: d[lang] })),
  };
  return normalizeReport(raw, lang, DEMO_TEXTS[id]);
}

export const DEMO_IDS: DemoId[] = ["social", "taxi", "shop"];

export function isDemoId(v: unknown): v is DemoId {
  return v === "social" || v === "taxi" || v === "shop";
}
