/* ---------------- deletion-request letter ---------------- */

export type LetterLang = "ru" | "ky" | "en";

export interface LetterInput {
  company: string;
  name: string;
  account: string;
  date: Date;
}

export function buildLetter(lang: LetterLang, i: LetterInput): { subject: string; body: string } {
  const name = i.name.trim() || (lang === "en" ? "[Your name]" : lang === "ky" ? "[Атың]" : "[Имя Фамилия]");
  const account = i.account.trim() || (lang === "en" ? "[account e-mail / phone]" : lang === "ky" ? "[аккаунттун e-mail / телефону]" : "[e-mail / телефон аккаунта]");
  const company = i.company.trim() || (lang === "en" ? "your service" : lang === "ky" ? "сиздин сервис" : "ваш сервис");
  const date = i.date.toLocaleDateString(lang === "en" ? "en-GB" : "ru-RU");

  if (lang === "en") {
    return {
      subject: "Request to erase my personal data",
      body: `Dear ${company} data protection team,

I am a user of ${company} and I am exercising my rights as a data subject. I request that you:

1. Erase all personal data you hold about me, including account data, activity history, location data and any copies shared with third parties.
2. Stop processing my personal data; I withdraw any consent I have given, including for advertising and analytics.
3. Tell me which third parties have received my data and notify them of this request.
4. Confirm the erasure to me in writing.

To identify my account: ${account}.

Please respond within the time limit set by the applicable data protection law.

Kind regards,
${name}
${date}`,
    };
  }

  if (lang === "ky") {
    return {
      subject: "Жеке маалыматтарымды өчүрүү боюнча өтүнүч",
      body: `Саламатсызбы!

Мен, ${name}, «${company}» сервисинин колдонуучусумун жана жеке маалыматтардын субъекти катары төмөнкүлөрдү талап кылам:

1. Мен тууралуу чогултулган жана иштетилген бардык жеке маалыматтарды өчүрүүнү, анын ичинде аккаунттун маалыматтарын, аракеттердин тарыхын, жайгашкан жер тууралуу маалыматты жана үчүнчү жактарга берилген көчүрмөлөрдү.
2. Маалыматтарымды иштетүүнү токтотууну. Мен берген бардык макулдуктарды, анын ичинде жарнама жана аналитика үчүн, кайтарып алам.
3. Маалыматтарым кайсы үчүнчү жактарга берилгенин билдирүүнү жана аларга менин талабым тууралуу кабарлоону.
4. Өчүрүлгөнүн жазуу жүзүндө тастыктоону.

Аккаунтту аныктоо үчүн: ${account}.

Жеке маалыматтар жөнүндө мыйзамдарда белгиленген мөөнөттө жооп берүүңүздү суранам.

Урматтоо менен,
${name}
${date}`,
    };
  }

  return {
    subject: "Запрос на удаление персональных данных",
    body: `Здравствуйте!

Я, ${name}, являюсь пользователем сервиса «${company}» и как субъект персональных данных прошу:

1. Удалить все персональные данные обо мне, которые вы собираете и обрабатываете, включая данные аккаунта, историю действий, сведения о местоположении, а также копии, переданные третьим лицам.
2. Прекратить обработку моих данных. Я отзываю все ранее данные согласия, в том числе на рекламу и аналитику.
3. Сообщить, каким третьим лицам передавались мои данные, и уведомить их о моём требовании.
4. Письменно подтвердить удаление.

Для идентификации аккаунта: ${account}.

Прошу ответить в срок, установленный законодательством о персональных данных.

С уважением,
${name}
${date}`,
  };
}
